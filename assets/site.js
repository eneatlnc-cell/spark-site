/* ============================================================
   Spark — simple site · shared JS
   Generated by Trae Work
   1) DOWNLOAD config — the single place APK store URLs live.
   2) Lightweight EN / 中文 toggle (data-i18n keys per page).
   3) Mobile nav + scroll reveal.
   ============================================================ */

(function () {
  "use strict";

  /* ---- 1. DOWNLOAD config (mirror of old site.js, single source) ---- */
  var DOWNLOAD = {
    engine: {
      version: "v3.82.2",
      code: "116",
      url: "https://github.com/eneatlnc-cell/Spark/releases/download/v3.82.2/Engine-3.82.2-release.apk"
    },
    vault: {
      version: "v3.78.0",
      code: "41",
      url: "https://github.com/eneatlnc-cell/Spark/releases/download/v3.78.1/Vault-3.78.0-release.apk"
    }
  };

  function bindDownloads() {
    document.querySelectorAll("[data-download]").forEach(function (el) {
      var cfg = DOWNLOAD[el.getAttribute("data-download")];
      if (!cfg) return;
      if (cfg.url) {
        el.setAttribute("href", cfg.url);
        el.setAttribute("target", "_blank");
        el.setAttribute("rel", "noopener");
      } else {
        el.classList.add("disabled");
        el.setAttribute("aria-disabled", "true");
        el.querySelector(".go").textContent = "APK 审核中";
      }
    });
  }

  /* ---- 2. Lightweight i18n ---- */
  var pageKey = document.body.getAttribute("data-page") || "index";
  var I18N = (window.SITE_I18N && window.SITE_I18N[pageKey]) || {};

  function applyLang(lang) {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      var dict = I18N[key];
      if (dict && dict[lang]) el.textContent = dict[lang];
    });
    updateSwitch(lang);
  }
  function updateSwitch(lang) {
    document.querySelectorAll(".lang-switch button").forEach(function (b) {
      b.classList.toggle("on", b.getAttribute("data-set") === lang);
    });
  }

  /* ---- 3. Mobile nav ---- */
  function initNav() {
    var burger = document.querySelector(".burger");
    var links = document.querySelector(".nav-links");
    if (burger && links) {
      burger.addEventListener("click", function () { links.classList.toggle("open"); });
      links.querySelectorAll("a").forEach(function (a) {
        a.addEventListener("click", function () { links.classList.remove("open"); });
      });
    }
  }

  /* ---- 4. Scroll reveal ---- */
  function initReveal() {
    var els = document.querySelectorAll(".reveal");
    if (!("IntersectionObserver" in window) || els.length === 0) return;
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) {
        if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); }
      });
    }, { threshold: 0.12 });
    els.forEach(function (el) { io.observe(el); });
  }

  /* ---- Boot ---- */
  document.addEventListener("DOMContentLoaded", function () {
    bindDownloads();
    initNav();
    initReveal();

    // i18n wiring
    document.querySelectorAll(".lang-switch button").forEach(function (b) {
      b.addEventListener("click", function () { applyLang(b.getAttribute("data-set")); });
    });
    applyLang("en");
  });

  window.SparkConfig = { download: DOWNLOAD };
})();